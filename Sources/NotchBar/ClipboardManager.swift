import AppKit
import ImageIO

let clipCacheDir: URL = FileManager.default.urls(for: .cachesDirectory, in: .userDomainMask)[0]
    .appendingPathComponent("NotchBar/Clips", isDirectory: true)

struct ClipItem: Identifiable, Equatable {
    enum Kind: Equatable {
        case text(String)
        case image(URL)
        case files([URL])
    }

    let id = UUID()
    var date = Date()
    let kind: Kind
    let thumbnail: NSImage?
    let detail: String
    let signature: Int

    static func == (a: ClipItem, b: ClipItem) -> Bool { a.id == b.id }

    var isLink: Bool {
        guard case .text(let s) = kind else { return false }
        let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
        return !t.contains(" ") && (t.hasPrefix("http://") || t.hasPrefix("https://"))
    }

    var title: String {
        switch kind {
        case .text: return isLink ? "Enlace copiado" : "Texto copiado"
        case .image: return "Imagen copiada"
        case .files(let urls): return urls.count == 1 ? "Archivo copiado" : "\(urls.count) archivos copiados"
        }
    }
}

@MainActor
final class ClipboardManager: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published private(set) var lastCopiedID: UUID?

    var onNewItem: ((ClipItem) -> Void)?

    private let maxItems = 15
    private let lifetime: TimeInterval = 2 * 60 * 60
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let work = DispatchQueue(label: "notchbar.clipboard", qos: .utility)

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
    ]

    func start() {
        let fm = FileManager.default
        try? fm.removeItem(at: clipCacheDir)
        try? fm.createDirectory(at: clipCacheDir, withIntermediateDirectories: true)

        scheduleNextCheck()
    }

    private func scheduleNextCheck() {
        let idle = CGEventSource.secondsSinceLastEventType(.combinedSessionState,
                                                           eventType: CGEventType(rawValue: ~0)!)
        let interval: TimeInterval = idle > 60 ? 3 : 1
        let t = Timer(timeInterval: interval, repeats: false) { [weak self] _ in
            MainActor.assumeIsolated {
                self?.check()
                self?.purgeExpired()
                self?.scheduleNextCheck()
            }
        }
        t.tolerance = interval * 0.3
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }


    private func check() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        let types = pb.types ?? []
        if types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }) { return }

        if types.contains(.fileURL),
           let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let detail = urls.count == 1 ? urls[0].deletingLastPathComponent().path
                                         : urls.map(\.lastPathComponent).joined(separator: ", ")
            insert(ClipItem(kind: .files(urls),
                            thumbnail: NSWorkspace.shared.icon(forFile: urls[0].path),
                            detail: detail,
                            signature: urls.hashValue), notify: true)
            return
        }

        if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff) {
            processImage(data)
            return
        }

        if let s = pb.string(forType: .string),
           !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let text = s.count > 20_000 ? String(s.prefix(20_000)) : s
            insert(ClipItem(kind: .text(text), thumbnail: nil,
                            detail: "\(s.count) caracteres",
                            signature: text.hashValue), notify: true)
        }
    }

    private func processImage(_ data: Data) {
        work.async { [weak self] in
          autoreleasepool {
            var hasher = Hasher()
            data.withUnsafeBytes { hasher.combine(bytes: $0) }
            let signature = hasher.finalize()

            let opts = [kCGImageSourceCreateThumbnailFromImageAlways: true,
                        kCGImageSourceCreateThumbnailWithTransform: true,
                        kCGImageSourceThumbnailMaxPixelSize: 212] as CFDictionary
            guard let src = CGImageSourceCreateWithData(data as CFData, nil),
                  let thumb = CGImageSourceCreateThumbnailAtIndex(src, 0, opts) else { return }

            var detail = "Imagen"
            if let props = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any],
               let w = props[kCGImagePropertyPixelWidth] as? Int,
               let h = props[kCGImagePropertyPixelHeight] as? Int {
                detail = "\(w) × \(h)"
            }

            let isPNG = data.starts(with: [0x89, 0x50, 0x4E, 0x47])
            let png = isPNG ? data : NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:])
            let url = clipCacheDir.appendingPathComponent(Self.fileName())
            guard let png, (try? png.write(to: url)) != nil else { return }

            let thumbImage = NSImage(cgImage: thumb, size: NSSize(width: thumb.width, height: thumb.height))
            DispatchQueue.main.async {
                self?.insert(ClipItem(kind: .image(url), thumbnail: thumbImage,
                                      detail: detail, signature: signature), notify: true)
            }
          }
        }
    }

    nonisolated private static func fileName() -> String {
        let f = DateFormatter()
        f.dateFormat = "yyyy-MM-dd 'a las' HH.mm.ss"
        return "Imagen \(f.string(from: Date())) \(UUID().uuidString.prefix(4)).png"
    }

    private func insert(_ item: ClipItem, notify: Bool) {
        var item = item
        if let idx = items.firstIndex(where: { $0.signature == item.signature }) {
            deleteFile(of: item)
            item = items.remove(at: idx)
            item.date = Date()
        }
        items.insert(item, at: 0)
        while items.count > maxItems {
            deleteFile(of: items.removeLast())
        }
        if notify { onNewItem?(item) }
    }


    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text(let s):
            pb.setString(s, forType: .string)
        case .image(let url):
            if let img = NSImage(contentsOf: url) { pb.writeObjects([img]) }
        case .files(let urls):
            pb.writeObjects(urls as [NSURL])
        }
        lastChangeCount = pb.changeCount

        if let idx = items.firstIndex(of: item) {
            items.insert(items.remove(at: idx), at: 0)
        }
        lastCopiedID = item.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            if self?.lastCopiedID == item.id { self?.lastCopiedID = nil }
        }
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        deleteFile(of: item)
    }

    private func purgeExpired() {
        guard !items.isEmpty else { return }
        let limit = Date().addingTimeInterval(-lifetime)
        let expired = items.filter { $0.date < limit }
        guard !expired.isEmpty else { return }
        expired.forEach(deleteFile(of:))
        items.removeAll { $0.date < limit }
    }

    func clear() {
        items.forEach(deleteFile(of:))
        items.removeAll()
    }

    func dragProvider(for item: ClipItem) -> NSItemProvider {
        switch item.kind {
        case .text(let s):
            return NSItemProvider(object: s as NSString)
        case .image(let url):
            return NSItemProvider(contentsOf: url) ?? NSItemProvider()
        case .files(let urls):
            return NSItemProvider(contentsOf: urls[0]) ?? NSItemProvider()
        }
    }

    private func deleteFile(of item: ClipItem) {
        if case .image(let url) = item.kind, url.path.hasPrefix(clipCacheDir.path) {
            try? FileManager.default.removeItem(at: url)
        }
    }
}
